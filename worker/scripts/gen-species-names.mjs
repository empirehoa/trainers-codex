#!/usr/bin/env node
// Regenerates worker/src/species-names.ts from src/data/pokemon-data.json.
//
// The worker cannot import from ../src at deploy time (wrangler bundles only
// worker/), so the species display names it needs for listing-title
// sanitization (pf-catalog.ts) are committed as a generated module. Run this
// after any data refresh:
//
//   node worker/scripts/gen-species-names.mjs
//
// worker/test/listing-name.test.ts asserts the generated array has exactly as
// many entries as the JSON, so drift fails CI instead of silently shipping a
// stale blocklist. Names are stored already normalized (see normalizeListing
// in pf-catalog.ts — this file mirrors that function on purpose so the
// generated list and the runtime matcher agree byte-for-byte).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const dataPath = resolve(here, '../../src/data/pokemon-data.json');
const outPath = resolve(here, '../src/species-names.ts');

/** Mirror of pf-catalog.ts normalizeListing: NFD, strip marks, lowercase, non-alnum → space. */
function normalize(s) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ').trim();
}

const raw = JSON.parse(readFileSync(dataPath, 'utf8'));
const entries = Array.isArray(raw) ? raw : Object.values(raw);
const names = entries.map((e) => {
  if (typeof e?.d !== 'string' || !e.d) throw new Error(`entry ${e?.i} has no display name`);
  return normalize(e.d);
});

const body = names.map((n) => `  ${JSON.stringify(n)},`).join('\n');
const out = `// GENERATED by worker/scripts/gen-species-names.mjs — do not edit by hand.
// Source: src/data/pokemon-data.json (${entries.length} entries). Each entry is the
// species display name normalized exactly as pf-catalog.ts normalizeListing()
// does (NFD, marks stripped, lowercase, punctuation → space). The array keeps
// one entry per JSON entry so its length is a drift check; the matcher builds
// a Set.
export const SPECIES_NAME_COUNT = ${entries.length};
export const SPECIES_NAMES: readonly string[] = [
${body}
];
`;
writeFileSync(outPath, out);
console.log(`wrote ${outPath}: ${entries.length} names`);
